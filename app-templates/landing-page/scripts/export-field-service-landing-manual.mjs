import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { composeCmsFamily } from "./compose-cms-family.mjs";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const landingRoot = path.resolve(scriptsDir, "..");
const specPath = path.join(landingRoot, "compositions/specs/field-service-operations.spec.json");
const contentPath = path.join(landingRoot, "content/field-service-operations/parameter-values.json");
const defaultOutputDir = path.join(landingRoot, "dist/manual-upload/field-service-operations");

const flattenTemplates = (templates = []) =>
  templates.flatMap((template) => [template, ...flattenTemplates(template.children || [])]);

const digest = (value) => crypto.createHash("sha256").update(value).digest("hex");

const writeJson = async (file, value) => {
  await fs.writeFile(file, `${JSON.stringify(value, null, 2)}\n`, "utf8");
};

const assertOutput = (target) => {
  const allowed = `${path.join(landingRoot, "dist", "manual-upload")}${path.sep}`;
  if (!target.startsWith(allowed)) {
    throw new Error("Field Service manual output must stay under landing-page/dist/manual-upload");
  }
};

const exists = async (target) => {
  try {
    await fs.access(target);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
};

const replaceDirectory = async (target, staging, backup) => {
  const hasExisting = await exists(target);
  try {
    if (hasExisting) await fs.rename(target, backup);
    await fs.rename(staging, target);
    if (hasExisting) await fs.rm(backup, { recursive: true, force: true });
  } catch (error) {
    await fs.rm(target, { recursive: true, force: true });
    if (hasExisting) await fs.rename(backup, target);
    throw error;
  }
};

const packageReadme = (codes) => `# Field Service Operations manual CMS family

Generated by \`scripts/export-field-service-landing-manual.mjs\` from the
repo-owned Field Service spec and content pack. Do not edit this directory by
hand.

- Root: \`FIELD_SERVICE_LANDING\`
- Templates: ${codes.length}
- URL: \`/industries/field-service\`
- Upload is intentionally separate and must start with \`--dry-run\`.
- Parent links, root includes, enabled templates, and PageContext are not
  changed by the flat uploader.

## Operator flow

From the repository root:

\`\`\`bash
node app-templates/landing-page/scripts/export-field-service-landing-manual.mjs
node app-templates/landing-page/scripts/field-service-landing-manual-check.mjs

SERVICEWAND_API_KEY="$SERVICEWAND_API_KEY" \\
node app-templates/landing-page/scripts/upload-cms-family.mjs \\
  --out app-templates/landing-page/dist/manual-upload/field-service-operations \\
  --base-url https://dev-1.servicewand.com/core \\
  --org SYSTEM \\
  --require-existing \\
  --expected-root-id "$FIELD_SERVICE_ROOT_ID" \\
  --dry-run
\`\`\`

Review all 15 resolved codes and IDs. Only after explicit approval, repeat the
same command with \`--live\` instead of \`--dry-run\`.
`;

export async function exportFieldServiceLandingManual(options = {}) {
  const target = path.resolve(options.outputDir || defaultOutputDir);
  assertOutput(target);
  const suffix = crypto.randomBytes(6).toString("hex");
  const staging = `${target}.staging-${suffix}`;
  const backup = `${target}.backup-${suffix}`;
  await fs.rm(staging, { recursive: true, force: true });

  try {
    const family = composeCmsFamily({ specPath, outDir: staging, valuesPath: contentPath });
    execFileSync(process.execPath, [path.join(scriptsDir, "validate-cms-family.mjs"), "--out", staging], {
      cwd: path.resolve(landingRoot, "../.."),
      stdio: options.quiet ? "ignore" : "inherit",
    });
    execFileSync(process.execPath, [path.join(scriptsDir, "render-cms-family-preview.mjs"), "--out", staging, "--file", "preview.html"], {
      cwd: path.resolve(landingRoot, "../.."),
      stdio: options.quiet ? "ignore" : "inherit",
    });

    const templates = [family.rootTemplate, ...flattenTemplates(family.children)];
    const templateCodes = templates.map((template) => template.code);
    const content = await fs.readFile(contentPath, "utf8");
    const spec = await fs.readFile(specPath, "utf8");
    await writeJson(path.join(staging, "manual-export-manifest.json"), {
      schemaVersion: 1,
      uploadPerformed: false,
      rootCode: family.rootTemplate.code,
      url: family.pageContext.url,
      templateCodes,
      appliedContentCodes: family.resolved.appliedContentCodes,
      sources: {
        spec: "compositions/specs/field-service-operations.spec.json",
        content: "content/field-service-operations/parameter-values.json",
      },
      sha256: { spec: digest(spec), content: digest(content) },
    });
    await fs.writeFile(path.join(staging, "README.md"), packageReadme(templateCodes), "utf8");
    await replaceDirectory(target, staging, backup);
    return { outputDir: target, family, templateCodes };
  } catch (error) {
    await fs.rm(staging, { recursive: true, force: true });
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = await exportFieldServiceLandingManual();
  console.log(`export-field-service-landing-manual ok: ${path.relative(process.cwd(), result.outputDir)} upload=false`);
  console.log(`templates: ${result.templateCodes.join(", ")}`);
}
